/*
 * OhhO Build — exporters.
 *
 * Turns a finished design into the artifacts the rest of the OhhO stack
 * consumes: a URDF, a Gazebo simulation world, an OhhO Frame deployment
 * profile, and an order-ready bill of materials (CSV + JSON). All generators
 * are pure string builders; downloadFile() is the only browser-touching bit.
 */

import { getPart, type Category, type Part } from "./catalog";
import { selectedIds, singleSelected, type Design } from "./design";
import { computeMetrics, type Metrics } from "./engine";

function slug(name: string): string {
  return name.trim().toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "") || "omnibot";
}

function resolveCat(design: Design, cat: Category): Part | undefined {
  const id = singleSelected(design, cat);
  return id ? getPart(id) : undefined;
}

// ── BOM (bill of materials) ──────────────────────────────────────────────────

export interface BomRow {
  category: Category;
  name: string;
  brand: string;
  qty: number;
  unitPrice: number;
  lineTotal: number;
  leadTimeDays: number;
  supplier: string;
  supplierUrl: string;
}

export function buildBom(design: Design): BomRow[] {
  const rows: BomRow[] = [];
  for (const cat of Object.keys(design.selection) as Category[]) {
    // collapse identical ids into a quantity (only sensors can repeat today)
    const counts = new Map<string, number>();
    for (const id of selectedIds(design, cat)) counts.set(id, (counts.get(id) ?? 0) + 1);
    for (const [id, qty] of Array.from(counts.entries())) {
      const p = getPart(id);
      if (!p) continue;
      rows.push({
        category: cat,
        name: p.name,
        brand: p.brand,
        qty,
        unitPrice: p.price,
        lineTotal: p.price * qty,
        leadTimeDays: p.leadTimeDays,
        supplier: p.supplier,
        supplierUrl: p.supplierUrl,
      });
    }
  }
  return rows;
}

export function bomToCsv(design: Design): string {
  const rows = buildBom(design);
  const m = computeMetrics(design);
  const header = ["Category", "Part", "Brand", "Qty", "Unit Price (USD)", "Line Total (USD)", "Lead Time (days)", "Supplier", "URL"];
  const lines = rows.map((r) =>
    [r.category, r.name, r.brand, r.qty, r.unitPrice, r.lineTotal, r.leadTimeDays, r.supplier, r.supplierUrl]
      .map(csvCell)
      .join(","),
  );
  lines.push("");
  lines.push(`,,,,,${m.totalPrice},${m.maxLeadTimeDays} (max lead),,`);
  return [header.join(","), ...lines].join("\n");
}

function csvCell(v: string | number): string {
  const s = String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function designToJson(design: Design): string {
  const m = computeMetrics(design);
  return JSON.stringify(
    {
      name: design.name,
      generatedBy: "OhhO Build",
      requirements: design.requirements,
      bom: buildBom(design),
      metrics: stripParts(m),
    },
    null,
    2,
  );
}

function stripParts(m: Metrics) {
  const { parts, ...rest } = m;
  return rest;
}

// ── URDF ─────────────────────────────────────────────────────────────────────

export function buildUrdf(design: Design): string {
  const m = computeMetrics(design);
  const name = slug(design.name);
  const base = resolveCat(design, "base");
  const arm = resolveCat(design, "arm");
  const gripper = resolveCat(design, "gripper");
  const sensors = selectedIds(design, "sensor").map(getPart).filter(Boolean) as Part[];

  const lines: string[] = [];
  lines.push(`<?xml version="1.0"?>`);
  lines.push(`<!-- Generated by OhhO Build — ${design.name} -->`);
  lines.push(`<!-- Hands off to OhhO Frame / View / Serve with zero re-modeling. -->`);
  lines.push(`<robot name="${name}">`);

  // base_link
  if (base) {
    const [l, w, h] = base.size;
    lines.push(`  <link name="base_link">`);
    lines.push(`    <visual>`);
    lines.push(`      <geometry><box size="${l} ${w} ${h}"/></geometry>`);
    lines.push(`      <material name="chassis"><color rgba="0.06 0.07 0.09 1"/></material>`);
    lines.push(`    </visual>`);
    lines.push(`    <collision><geometry><box size="${l} ${w} ${h}"/></geometry></collision>`);
    lines.push(`    <inertial><mass value="${base.mass}"/><inertia ixx="0.1" ixy="0" ixz="0" iyy="0.1" iyz="0" izz="0.1"/></inertial>`);
    lines.push(`  </link>`);

    // four wheels from the drive kit
    const drive = resolveCat(design, "drive");
    if (drive) {
      const wr = Math.max(0.03, drive.size[2] / 2);
      const corners: [number, number, string][] = [
        [l / 2 - wr, w / 2, "fl"],
        [l / 2 - wr, -w / 2, "fr"],
        [-(l / 2 - wr), w / 2, "rl"],
        [-(l / 2 - wr), -w / 2, "rr"],
      ];
      for (const [x, y, tag] of corners) {
        lines.push(`  <link name="wheel_${tag}_link">`);
        lines.push(`    <visual><geometry><cylinder radius="${wr.toFixed(3)}" length="${(drive.size[2] * 0.4).toFixed(3)}"/></geometry></visual>`);
        lines.push(`  </link>`);
        lines.push(`  <joint name="wheel_${tag}_joint" type="continuous">`);
        lines.push(`    <parent link="base_link"/><child link="wheel_${tag}_link"/>`);
        lines.push(`    <origin xyz="${x.toFixed(3)} ${y.toFixed(3)} ${(-h / 2).toFixed(3)}" rpy="1.5708 0 0"/>`);
        lines.push(`    <axis xyz="0 0 1"/>`);
        lines.push(`  </joint>`);
      }
    }
  }

  // arm as a chain of `dof` revolute joints climbing the reach
  if (arm) {
    const dof = arm.dof ?? 6;
    const seg = (arm.reach ?? 0.5) / dof;
    let parent = "base_link";
    let z = base ? base.size[2] / 2 : 0;
    for (let i = 1; i <= dof; i++) {
      const link = `arm_link_${i}`;
      lines.push(`  <link name="${link}">`);
      lines.push(`    <visual><geometry><box size="0.04 0.04 ${seg.toFixed(3)}"/></geometry><material name="arm"><color rgba="0.83 0.84 0.86 1"/></material></visual>`);
      lines.push(`  </link>`);
      lines.push(`  <joint name="arm_joint_${i}" type="revolute">`);
      lines.push(`    <parent link="${parent}"/><child link="${link}"/>`);
      lines.push(`    <origin xyz="0 0 ${i === 1 ? z.toFixed(3) : seg.toFixed(3)}" rpy="0 0 0"/>`);
      lines.push(`    <axis xyz="${i % 2 === 0 ? "1 0 0" : "0 0 1"}"/>`);
      lines.push(`    <limit lower="-3.14" upper="3.14" effort="10" velocity="2"/>`);
      lines.push(`  </joint>`);
      parent = link;
      z = 0;
    }
    if (gripper) {
      lines.push(`  <link name="gripper_link">`);
      lines.push(`    <visual><geometry><box size="${gripper.size[0]} ${gripper.size[1]} ${gripper.size[2]}"/></geometry></visual>`);
      lines.push(`  </link>`);
      lines.push(`  <joint name="gripper_joint" type="fixed"><parent link="${parent}"/><child link="gripper_link"/><origin xyz="0 0 ${seg.toFixed(3)}"/></joint>`);
    }
  }

  // sensors mounted on the base
  sensors.forEach((s, i) => {
    const link = `${sensorFrame(s)}_${i}`;
    lines.push(`  <link name="${link}">`);
    lines.push(`    <visual><geometry><box size="${s.size[0]} ${s.size[1]} ${s.size[2]}"/></geometry></visual>`);
    lines.push(`  </link>`);
    lines.push(`  <joint name="${link}_joint" type="fixed"><parent link="base_link"/><child link="${link}"/><origin xyz="${(base ? base.size[0] / 2 - 0.03 : 0).toFixed(3)} 0 ${(base ? base.size[2] / 2 + 0.02 + i * 0.03 : 0).toFixed(3)}"/></joint>`);
  });

  lines.push(`</robot>`);
  lines.push(``);
  lines.push(`<!-- design mass: ${m.totalMass} kg · reach: ${m.reach} m · top speed: ${m.topSpeed} m/s -->`);
  return lines.join("\n");
}

function sensorFrame(p: Part): string {
  if (p.id.includes("lidar")) return "lidar_link";
  if (p.id.includes("astra") || p.id.includes("depth")) return "depth_camera_link";
  if (p.id.includes("imu")) return "imu_link";
  return "camera_link";
}

// ── Gazebo simulation world ───────────────────────────────────────────────────

export function buildWorld(design: Design): string {
  const name = slug(design.name);
  const env = design.requirements.environment;
  return [
    `<?xml version="1.0"?>`,
    `<!-- Generated by OhhO Build — ${design.name} (${env}) -->`,
    `<sdf version="1.9">`,
    `  <world name="${name}_world">`,
    `    <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor></physics>`,
    `    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>`,
    `    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>`,
    `    <light type="directional" name="sun">`,
    `      <cast_shadows>true</cast_shadows><direction>-0.5 0.1 -0.9</direction>`,
    `    </light>`,
    `    <model name="ground_plane"><static>true</static>`,
    `      <link name="link"><collision name="c"><geometry><plane><normal>0 0 1</normal></plane></geometry></collision>`,
    `      <visual name="v"><geometry><plane><normal>0 0 1</normal><size>50 50</size></plane></geometry></visual></link>`,
    `    </model>`,
    `    <!-- spawn the OhhO Build robot from its generated URDF -->`,
    `    <include><uri>model://${name}</uri><pose>0 0 0.1 0 0 0</pose></include>`,
    `  </world>`,
    `</sdf>`,
  ].join("\n");
}

// ── OhhO Frame deployment profile ─────────────────────────────────────────────

export function buildDeployProfile(design: Design): string {
  const m = computeMetrics(design);
  const name = slug(design.name);
  const compute = resolveCat(design, "compute");
  const hasGpu = (compute?.tops ?? 0) >= 40;
  const lines: string[] = [];
  lines.push(`# OhhO Frame deployment profile — generated by OhhO Build`);
  lines.push(`# Robot: ${design.name}`);
  lines.push(`OMNIBOT_NAME=${name}`);
  lines.push(`OMNIBOT_ENVIRONMENT=${design.requirements.environment}`);
  lines.push(`DEPLOY_MODE=${hasGpu ? "single" : "multi"}`);
  lines.push(`ROS_DOMAIN_ID=30`);
  lines.push(`# compute`);
  lines.push(`COMPUTE=${compute?.id ?? "none"}`);
  lines.push(`COMPUTE_TOPS=${m.tops}`);
  lines.push(`ONBOARD_VLA=${hasGpu ? "true" : "false"}`);
  lines.push(`# subsystems`);
  for (const cat of ["base", "drive", "power", "arm", "gripper"] as Category[]) {
    const p = resolveCat(design, cat);
    if (p) lines.push(`${cat.toUpperCase()}=${p.id}`);
  }
  lines.push(`SENSORS=${selectedIds(design, "sensor").join(",") || "none"}`);
  lines.push(`# derived`);
  lines.push(`TOTAL_MASS_KG=${m.totalMass}`);
  lines.push(`PAYLOAD_KG=${m.usablePayload}`);
  lines.push(`RUNTIME_H=${m.runtime}`);
  lines.push(`TOP_SPEED_MS=${m.topSpeed}`);
  return lines.join("\n");
}

// ── browser download helper ───────────────────────────────────────────────────

export function downloadFile(filename: string, contents: string, mime = "text/plain"): void {
  if (typeof window === "undefined") return;
  const blob = new Blob([contents], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

